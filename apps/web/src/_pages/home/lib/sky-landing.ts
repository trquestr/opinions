/*
 * Посадка капель дня на звёзды ночи — общий стол двух сцен (起 → 承).
 * Ночная сцена каждый кадр пишет сюда экранные места звёзд, на которые садятся капли (семь звёзд ковша, затем
 * самые яркие фоновые в кадре), и радиус капли в конце пути. Сцена «Облака» ведёт к этим местам свои капли,
 * а ночная рисует на тех же местах свои капли-двойники и гасит их, пока разгораются звёзды. Так при смене сцен
 * на экране ничего не подменяется: капля долетает, сжимается в точку и загорается звездой.
 * Массивы выделены один раз: в кадре в них только пишут (требование 60 FPS).
 */

/** Больше целей не бывает: столько капель у сцены «Облака» на компьютере. */
export const LANDING_CAPACITY = 44;

export interface SkyLanding {
  /** Сколько целей опубликовала ночная сцена; 0 — ночь не готова, капли не садятся. */
  count: number;
  /** Сколько целей заняли капли дня: столько двойников рисует ночная сцена. */
  claimed: number;
  /** Экранные места целей и радиус севшей капли, CSS px. */
  readonly x: Float32Array;
  readonly y: Float32Array;
  readonly radius: Float32Array;
}

export function createSkyLanding(): SkyLanding {
  return {
    count: 0,
    claimed: 0,
    x: new Float32Array(LANDING_CAPACITY),
    y: new Float32Array(LANDING_CAPACITY),
    radius: new Float32Array(LANDING_CAPACITY),
  };
}

/** Один стол на страницу: сцены запускаются порознь (свои драйверы) и встречаются только здесь. */
export const skyLanding: SkyLanding = createSkyLanding();
