/*
 * Гравюрные детали ночной сцены (承): далёкий фон — картинки на небе, проступающие точками.
 * Файлы готовит scripts/prepare_night_details.py.
 *
 * Детали висят на небе постоянно: направление на бесконечно далёкой сфере относительно взгляда прямо вперёд
 * (туда, где ковш). В кадр их вводит поворот неба: у каждой фигуры камера доворачивает небо в свою сторону
 * (lib/night/camera.ts, figureSkyTurn), и центр кадра встаёт примерно в (рыскание, тангаж):
 *   медведица (+12°, −8°),  плуг (−10°, −8°),  колесница (+12°, +8°),  шествие (−10°, +8°),  общий план (0°, 0°).
 * Поле зрения — около ±23° по горизонтали и ±17.5° по вертикали от центра кадра. Поэтому у каждой фигуры есть
 * угол неба, которого не видно ни из одного другого кадра фигуры: рыскание дальше ±14° и тангаж дальше ±9.5°.
 * Детали фигуры стоят в её углу; на общем плане их края выглядывают из углов экрана.
 * Фраза стоит сбоку на уровне глаз, детали — выше или ниже неё (тангаж дальше ±12° от центра неба).
 */

export interface NightDetail {
  readonly name: string;
  /** Рыскание, градусы: вправо положительное. */
  readonly yawDeg: number;
  /** Тангаж, градусы: вниз положительный. */
  readonly pitchDeg: number;
  /** Угловая ширина, градусы. */
  readonly widthDeg: number;
  /** Множитель яркости этой детали (по умолчанию 1): плотные гравюры приглушаются, бледные усиливаются. */
  readonly alpha?: number;
}

